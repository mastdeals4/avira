export const activeProducts = products
  .filter((product) => product.active)
  .sort((a, b) => a.category.localeCompare(b.category) || a.name_en.localeCompare(b.name_en));

const uniqueSorted = (values: string[]) => Array.from(new Set(values.filter(Boolean))).sort((a, b) => a.localeCompare(b));

export const productCategories = uniqueSorted(activeProducts.map((product) => product.category));

export const getProductSubCategories = (category = '') => uniqueSorted(
  activeProducts
    .filter((product) => !category || product.category === category)
    .map((product) => product.sub_category),
);

export const getProductBySlug = (slug: string) => activeProducts.find((product) => product.slug === slug) || null;

export const getFeaturedProducts = (limit = 6) => [...activeProducts]
  .sort((a, b) => a.created_at.localeCompare(b.created_at) || a.name_en.localeCompare(b.name_en))
  .slice(0, limit);

export const getRelatedProducts = (product: Product, limit = 3) => activeProducts
  .filter((candidate) => candidate.slug !== product.slug && candidate.category === product.category)
  .slice(0, limit);

export const filterProducts = ({ category = '', subCategory = '' }: { category?: string; subCategory?: string }) => activeProducts.filter((product) => (
  (!category || product.category === category)
  && (!subCategory || product.sub_category === subCategory)
));

export const searchProducts = (query: string, source: Product[] = activeProducts) => {
  const normalized = query.trim().toLowerCase();
  if (!normalized) return source;
  return source.filter((product) => [
    product.name_en,
    product.name_id,
    product.inn,
    product.category,
    product.sub_category,
    product.description_en,
    product.description_id,
    product.applications.join(' '),
  ].some((value) => value.toLowerCase().includes(normalized)));
};

export const getProductName = (product: Product, lang: 'en' | 'id') => (
  lang === 'id' ? product.name_id || product.name_en : product.name_en || product.name_id
);

export const getProductDescription = (product: Product, lang: 'en' | 'id') => (
  lang === 'id' ? product.description_id || product.description_en : product.description_en || product.description_id
);
